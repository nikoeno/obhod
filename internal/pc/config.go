// PathsConfig overrides the standard directories.
type PathsConfig struct {
	// Root puts every directory under one folder (portable mode, tests).
	// Empty means the per-user standard locations.
	Root string `yaml:"root"`
}

// SecretsConfig names the files in Paths.Secrets that hold sing-box outbounds.
// Their content is never logged and never part of app.yaml.
type SecretsConfig struct {
	Tunnel string `yaml:"tunnel"` // required; a sing-box outbound as JSON; default "tunnel.json"
	Proxy  string `yaml:"proxy"`  // optional second outbound (SOCKS/HTTP) as JSON
}

// LogConfig configures the app log.
type LogConfig struct {
	Level     string `yaml:"level"`       // debug | info | warn | error; default info
	File      string `yaml:"file"`        // file name inside Paths.Logs; default "splitter.log"
	MaxSizeMB int    `yaml:"max_size_mb"` // rotate at this size; default 10
	MaxFiles  int    `yaml:"max_files"`   // rotated files to keep; default 3
}

// Config is the content of app.yaml. Keys of the child sections are the
// snake_case names from their struct tags; the checker's sections have no
// tags, so their keys are the lowercase Go field names (for example
// checker.schedule.failthreshold).
type Config struct {
	Paths    PathsConfig     `yaml:"paths"`
	Secrets  SecretsConfig   `yaml:"secrets"`
	Analyzer analyzer.Config `yaml:"analyzer"`
	Checker  checker.Config  `yaml:"checker"`
	SingBox  singbox.Config  `yaml:"singbox"`
	Desync   desync.Config   `yaml:"desync"`
	Procman  procman.Config  `yaml:"procman"`
	Monitor  monitor.Config  `yaml:"monitor"`
	Status   status.Config   `yaml:"status"`
	Log      LogConfig       `yaml:"log"`
}

// DefaultConfig returns the configuration used for keys that app.yaml omits.
func DefaultConfig() Config {
	c := Config{
		Secrets:  SecretsConfig{Tunnel: "tunnel.json"},
		Analyzer: analyzer.DefaultConfig(),
		SingBox:  singbox.Config{BlockQUIC: true},
		Log:      LogConfig{Level: "info", File: "splitter.log", MaxSizeMB: 10, MaxFiles: 3},
	}
	c.SingBox.DNS.DirectDoH = c.Analyzer.DoH[0]
	return c
}

// LoadConfig reads app.yaml over DefaultConfig. Unknown keys are an error. A
// relative list path is resolved against the directory of the file.
func LoadConfig(path string) (Config, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return Config{}, fmt.Errorf("config: %w", err)
	}
	cfg, err := ParseConfig(bytes.NewReader(data))
	if err != nil {
		return Config{}, fmt.Errorf("config %s: %w", path, err)
	}
	dir := filepath.Dir(path)
	for _, l := range []*[]string{&cfg.Checker.Lists.Candidates, &cfg.Checker.Lists.Proxy, &cfg.Checker.Lists.Block} {
		for i, f := range *l {
			if !filepath.IsAbs(f) {
				(*l)[i] = filepath.Join(dir, f)
			}
		}
	}
	return cfg, nil
}

// ParseConfig decodes and validates a YAML document over DefaultConfig.
func ParseConfig(r io.Reader) (Config, error) {
	cfg := DefaultConfig()
	dec := yaml.NewDecoder(r)
	dec.KnownFields(true)
	if err := dec.Decode(&cfg); err != nil && !errors.Is(err, io.EOF) {
		return Config{}, err
	}
	if cfg.SingBox.DNS.DirectDoH == "" && len(cfg.Analyzer.DoH) > 0 {
		cfg.SingBox.DNS.DirectDoH = cfg.Analyzer.DoH[0]
	}
	if err := cfg.Validate(); err != nil {
		return Config{}, err
	}
	return cfg, nil
}

// Validate checks the cross-module rules.
func (c Config) Validate() error {
	var errs []error
	add := func(format string, a ...any) { errs = append(errs, fmt.Errorf(format, a...)) }

	if err := c.Analyzer.Validate(); err != nil {
		add("analyzer: %w", err)
	}
	if !plainFileName(c.Secrets.Tunnel) {
		add("secrets.tunnel: must be a plain file name inside the secrets directory, got %q", c.Secrets.Tunnel)
	}
	if c.Secrets.Proxy != "" && !plainFileName(c.Secrets.Proxy) {
		add("secrets.proxy: must be a plain file name inside the secrets directory, got %q", c.Secrets.Proxy)
	}
	if c.Checker.Netwatch.Salt != "" {
		add("checker.netwatch.salt: generated by the app, remove it")
	}
	// sing-box's final route is tunnel (see G6 in PLAN.md); the checker's default for
	// unknown candidates must agree, or a domain would change route with the first probe.
	if u := c.Checker.UnknownDefault; u != "" && u != route.Tunnel {
		add("checker.unknowndefault: must be %q until the sing-box final route is configurable, got %q", route.Tunnel, u)
	}
	if e := c.Desync.Engine; e != "" && e != desync.WinWS && e != desync.NFQWS {
		add("desync.engine: unknown engine %q", e)
	}
	if _, ok := parseLevel(c.Log.Level); !ok {
		add("log.level: must be debug, info, warn or error, got %q", c.Log.Level)
	}
	if !plainFileName(c.Log.File) {
		add("log.file: must be a plain file name inside the logs directory, got %q", c.Log.File)
	}
	if c.Log.MaxSizeMB < 1 || c.Log.MaxFiles < 1 {
		add("log: max_size_mb and max_files must be at least 1")
	}
	if c.SingBox.DNS.DirectDoH == "" {
		add("singbox.dns.direct_doh: required")
	} else if err := checkSingBox(c.SingBox); err != nil {
		// singbox.dns.direct_doh defaults to analyzer.doh[0], which must then be an IP URL too.
		add("singbox: %w", err)
	}
	if err := c.Desync.Check(); err != nil {
		add("desync: %w", err)
	}
	if err := c.Checker.Validate(); err != nil {
		add("%w", err)
	}
	if _, err := status.New(c.Status, nopSource{}, nil); err != nil {
		add("status: %w", err)
	}
	return errors.Join(errs...)
}

// checkSingBox renders a config for an empty table with a stand-in outbound,
// so the sing-box fields (TUN address, FakeIP range, Clash API, DoH server)
// fail when the config is loaded, not at connect time.
func checkSingBox(c singbox.Config) error {
	c.ClashSecret = "validate"
	_, err := singbox.Generate(c, singbox.Outbounds{Tunnel: json.RawMessage(`{"type":"direct"}`)}, route.Table{})
	return err
}

type nopSource struct{}

func (nopSource) Snapshot() status.Snapshot { return status.Snapshot{} }

func plainFileName(s string) bool {
	return s != "" && s != "." && s != ".." && !strings.ContainsAny(s, `/\:`)
}

func parseLevel(s string) (slog.Level, bool) {
	switch strings.ToLower(s) {
	case "debug":
		return slog.LevelDebug, true
	case "info", "":
		return slog.LevelInfo, true
	case "warn":
		return slog.LevelWarn, true
	case "error":
		return slog.LevelError, true
	}
	return 0, false
}
