package singbox

import (
	"encoding/json"
	"errors"
	"fmt"
	"net"
	"net/netip"
	"net/url"
	"sort"
	"strconv"
	"strings"

	"github.com/nikoejento/obhod/internal/lib/route"
)

// Errors returned by Generate.
var (
	ErrNoTunnel   = errors.New("singbox: tunnel outbound is missing")
	ErrNoProxy    = errors.New("singbox: table routes domains to proxy but no proxy outbound is set")
	ErrInvalidCfg = errors.New("singbox: invalid config")
)

// Outbound tags used in the generated config. Connections reported by the
// Clash API carry one of them as the last element of their chain.
const (
	TagDirect = "direct"
	TagDesync = "desync"
	TagTunnel = "tunnel"
	TagProxy  = "proxy"
)

const (
	tagTUN       = "tun-in"
	tagDNSDirect = "dns-direct"
	tagDNSFake   = "dns-fakeip"

	defaultClashAPI = "127.0.0.1:9090"
	defaultFakeIP   = "198.18.0.0/16"
	defaultTUNName  = "splitter"
	defaultTUNAddr  = "198.19.0.1/30"
	defaultStack    = "mixed"
	defaultLogLevel = "info"
)

// TUNConfig describes the TUN inbound. auto_route and strict_route are always on.
type TUNConfig struct {
	Name    string `yaml:"name"`    // interface name; default "splitter"
	Address string `yaml:"address"` // interface address in CIDR form; default 198.19.0.1/30
	Stack   string `yaml:"stack"`   // system | gvisor | mixed; default mixed
}

// DNSConfig describes name resolution.
type DNSConfig struct {
	// DirectDoH is the DoH server (an IP address or an https URL with an IP host)
	// used for domains that are routed direct or desync. Required.
	DirectDoH string `yaml:"direct_doh"`
	// FakeIPRange is the IPv4 FakeIP range for all other domains; default 198.18.0.0/16.
	FakeIPRange string `yaml:"fake_ip_range"`
}

// Config holds everything Generate needs besides the outbounds and the table.
type Config struct {
	Binary       string    `yaml:"binary"`        // path to sing-box
	TUN          TUNConfig `yaml:"tun"`           // interface name, address, stack
	DNS          DNSConfig `yaml:"dns"`           // direct DoH server, FakeIP range
	ClashAPI     string    `yaml:"clash_api"`     // loopback listen address, default "127.0.0.1:9090"
	ClashSecret  string    `yaml:"-"`             // generated by the app at each start; never set by the user
	OwnProcesses []string  `yaml:"own_processes"` // process names routed direct (our binaries + desync engine)
	BlockQUIC    bool      `yaml:"block_quic"`    // reject udp/443 to force TCP fallback; the app config defaults it to true
	LogLevel     string    `yaml:"log_level"`     // default "info"
}

// Outbounds carries the raw outbound definitions read from secrets.
type Outbounds struct {
	Tunnel json.RawMessage // VLESS+Reality outbound; the tag is forced to "tunnel"
	Proxy  json.RawMessage // optional SOCKS/HTTP outbound; the tag is forced to "proxy"
}

type obj = map[string]any

// privateRanges stay on the physical network instead of entering the TUN.
var privateRanges = []string{
	"10.0.0.0/8", "169.254.0.0/16", "192.168.0.0/16", "fc00::/7", "fe80::/10",
}

// Generate returns the full sing-box JSON config. Equal input gives equal bytes.
func Generate(cfg Config, ob Outbounds, t route.Table) ([]byte, error) {
	if _, err := route.NewTable(t.NetworkID, t.Generated, t.Entries); err != nil {
		return nil, fmt.Errorf("singbox: invalid table: %w", err)
	}
	if len(ob.Tunnel) == 0 {
		return nil, ErrNoTunnel
	}
	if len(ob.Proxy) == 0 && len(t.Domains(route.Proxy)) > 0 {
		return nil, ErrNoProxy
	}

	api := orDefault(cfg.ClashAPI, defaultClashAPI)
	if err := checkLoopback(api); err != nil {
		return nil, err
	}
	dohHost, dohPort, dohPath, err := parseDoH(cfg.DNS.DirectDoH)
	if err != nil {
		return nil, err
	}
	fakeRange := orDefault(cfg.DNS.FakeIPRange, defaultFakeIP)
	if p, err := netip.ParsePrefix(fakeRange); err != nil || !p.Addr().Is4() {
		return nil, fmt.Errorf("%w: FakeIPRange %q must be an IPv4 prefix", ErrInvalidCfg, fakeRange)
	}
	tunAddr := orDefault(cfg.TUN.Address, defaultTUNAddr)
	if _, err := netip.ParsePrefix(tunAddr); err != nil {
		return nil, fmt.Errorf("%w: TUN address %q", ErrInvalidCfg, tunAddr)
	}

	tunnel, err := tagged(ob.Tunnel, TagTunnel)
	if err != nil {
		return nil, fmt.Errorf("singbox: tunnel outbound: %w", err)
	}
	outbounds := []any{
		obj{"type": "direct", "tag": TagDirect},
		obj{"type": "direct", "tag": TagDesync},
		tunnel,
	}
	if len(ob.Proxy) > 0 {
		proxy, err := tagged(ob.Proxy, TagProxy)
		if err != nil {
			return nil, fmt.Errorf("singbox: proxy outbound: %w", err)
		}
		outbounds = append(outbounds, proxy)
	}

	direct := t.Domains(route.Direct)
	desync := t.Domains(route.Desync)
	rules := []any{
		obj{"action": "sniff"},
		obj{"protocol": "dns", "action": "hijack-dns"},
	}
	if own := sortedUnique(cfg.OwnProcesses); len(own) > 0 {
		rules = append(rules, obj{"process_name": own, "action": "route", "outbound": TagDirect})
	}
	if cfg.BlockQUIC {
		rules = append(rules, obj{"network": "udp", "port": 443, "action": "reject"})
	}
	if d := t.Domains(route.Block); len(d) > 0 {
		rules = append(rules, obj{"domain_suffix": d, "action": "reject"})
	}
	for _, r := range []struct {
		domains []string
		tag     string
	}{
		{t.Domains(route.Proxy), TagProxy},
		{t.Domains(route.Tunnel), TagTunnel},
		{desync, TagDesync},
		{direct, TagDirect},
	} {
		if len(r.domains) > 0 {
			rules = append(rules, obj{"domain_suffix": r.domains, "action": "route", "outbound": r.tag})
		}
	}

	dnsRules := []any{}
	if both := sortedUnique(append(append([]string(nil), direct...), desync...)); len(both) > 0 {
		dnsRules = append(dnsRules, obj{"domain_suffix": both, "action": "route", "server": tagDNSDirect})
	}

	// sing-box forbids a fakeip default server, so FakeIP is selected by query
	// type. HTTPS/SVCB would otherwise leak the name to the direct server.
	dnsRules = append(dnsRules,
		obj{"query_type": []string{"HTTPS", "SVCB"}, "action": "reject"},
		obj{"query_type": []string{"A", "AAAA"}, "action": "route", "server": tagDNSFake},
	)

	doc := obj{
		"log": obj{"level": orDefault(cfg.LogLevel, defaultLogLevel), "timestamp": true},
		"dns": obj{
			"servers": []any{
				obj{"type": "https", "tag": tagDNSDirect, "server": dohHost, "server_port": dohPort, "path": dohPath},
				obj{"type": "fakeip", "tag": tagDNSFake, "inet4_range": fakeRange},
			},
			"rules":    dnsRules,
			"final":    tagDNSDirect,
			"strategy": "ipv4_only",
		},
		"inbounds": []any{obj{
			"type":                  "tun",
			"tag":                   tagTUN,
			"interface_name":        orDefault(cfg.TUN.Name, defaultTUNName),
			"address":               []string{tunAddr},
			"auto_route":            true,
			"strict_route":          true,
			"stack":                 orDefault(cfg.TUN.Stack, defaultStack),
			"route_exclude_address": privateRanges,
		}},
		"outbounds": outbounds,
		"route": obj{
			"rules":                   rules,
			"final":                   TagTunnel,
			"auto_detect_interface":   true,
			"default_domain_resolver": obj{"server": tagDNSDirect},
		},
		"experimental": obj{
			"clash_api": obj{"external_controller": api, "secret": cfg.ClashSecret},
		},
	}
	out, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("singbox: marshal: %w", err)
	}
	return append(out, '\n'), nil
}

func orDefault(s, def string) string {
	if s == "" {
		return def
	}
	return s
}

// tagged decodes a raw outbound, forces its tag and returns it as an object.
func tagged(raw json.RawMessage, tag string) (obj, error) {
	var o obj
	if err := json.Unmarshal(raw, &o); err != nil {
		return nil, fmt.Errorf("not a JSON object: %w", err)
	}
	if o == nil {
		return nil, errors.New("not a JSON object")
	}
	if _, ok := o["type"].(string); !ok {
		return nil, errors.New(`missing "type"`)
	}
	o["tag"] = tag
	return o, nil
}

func checkLoopback(addr string) error {
	host, _, err := net.SplitHostPort(addr)
	if err != nil {
		return fmt.Errorf("%w: ClashAPI %q: %v", ErrInvalidCfg, addr, err)
	}
	if host == "localhost" {
		return nil
	}
	ip, err := netip.ParseAddr(host)
	if err != nil || !ip.IsLoopback() {
		return fmt.Errorf("%w: ClashAPI %q must listen on a loopback address", ErrInvalidCfg, addr)
	}
	return nil
}

// parseDoH accepts "1.1.1.1" or "https://1.1.1.1[:port]/path" and returns host, port, path.
func parseDoH(s string) (host string, port int, path string, err error) {
	if s == "" {
		return "", 0, "", fmt.Errorf("%w: DNS.DirectDoH is empty", ErrInvalidCfg)
	}
	port, path = 443, "/dns-query"
	if !strings.Contains(s, "://") {
		s = "https://" + s
	}
	u, perr := url.Parse(s)
	if perr != nil || u.Scheme != "https" || u.Hostname() == "" {
		return "", 0, "", fmt.Errorf("%w: DNS.DirectDoH %q", ErrInvalidCfg, s)
	}
	if _, aerr := netip.ParseAddr(u.Hostname()); aerr != nil {
		return "", 0, "", fmt.Errorf("%w: DNS.DirectDoH host must be an IP address (no bootstrap resolver)", ErrInvalidCfg)
	}
	if p := u.Port(); p != "" {
		n, nerr := strconv.Atoi(p)
		if nerr != nil || n < 1 || n > 65535 {
			return "", 0, "", fmt.Errorf("%w: DNS.DirectDoH port %q", ErrInvalidCfg, p)
		}
		port = n
	}
	if u.Path != "" {
		path = u.Path
	}
	return u.Hostname(), port, path, nil
}

func sortedUnique(in []string) []string {
	m := make(map[string]struct{}, len(in))
	for _, s := range in {
		if s != "" {
			m[s] = struct{}{}
		}
	}
	out := make([]string, 0, len(m))
	for s := range m {
		out = append(out, s)
	}
	sort.Strings(out)
	return out
}
